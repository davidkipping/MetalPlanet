"""Render results_oblate.json as RESULTS.md (generated -- edit this script)."""
import json
import os

from scenario_oblate import (A_RS, B_IMPACT, BATCH_NPT, BATCH_NPV, F, N_PREC,
                             PER, RP, THETA_DEG, U1, U2, W_LD)

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = {"metalplanet_fp64": "MetalPlanet fp64 (CPU)",
         "metalplanet_fp32": "MetalPlanet fp32 (GPU, Metal)",
         "squishyplanet": "squishyplanet 0.5.0 (JAX, fp64, CPU)",
         "jojo": "JoJo 0.1.0 (numpy, fp64)",
         "greenlantern": "GreenLantern 1.6 (OpenCL GPU, fp32)"}


def ms(s):
    return f"{s * 1e3:,.2f} ms" if s < 10 else f"{s:,.1f} s"


def main():
    r = json.load(open(os.path.join(HERE, "results_oblate.json")))
    L = ["<!-- GENERATED by benchmarks/oblate_compare/make_report_oblate.py -->", "",
         "# Oblate planets: cross-code benchmark", "",
         f"Machine: {r['machine']}, Python {r['python']}; run {r['started']} "
         f"(load average {r['load'][0]:.1f} at the start). See README.md here "
         "for the environment and the macOS build of GreenLantern.", "",
         f"Scenario: the spherical benchmark's transit (P = {PER} d, a/R* = {A_RS}, "
         f"b = {B_IMPACT}, area-equivalent Rp/R* = {RP}) with projected flattening "
         f"f = {F} and the long axis at {THETA_DEG:.0f} deg to the motion. Limb "
         f"darkening is the one profile every code expresses exactly: "
         f"I(mu) = 1 - {W_LD} (1 - mu^2), MetalPlanet's hybrid2 with its pole "
         f"weight 0, and the quadratic law (u1, u2) = ({U1}, {U2}) for the others. "
         "Circular orbit, instantaneous fluxes. Every code's parameter mapping "
         "was checked against the others before timing.", "",
         "## What each code covers", "",
         "| | MetalPlanet | squishyplanet | JoJo | GreenLantern |",
         "|---|---|---|---|---|",
         "| limb darkening, oblate planet | hybrid2/4/5 (even powers of mu + double poles) | polynomial, any order | quadratic | quadratic |",
         "| method | analytic (Green's theorem, partial fractions) | analytic (ALFM20 extension) | Green's theorem, numerical line integral (100 steps) | Green's theorem, Simpson's rule (2048 steps) |",
         "| precision | fp64 (CPU) and fp32 (GPU) | fp64 | fp64 | fp32 |",
         "| gradients | analytic VJP (fp32 kernel), autodiff (fp64) | JAX (forward Jacobian) | none | forward-mode duals |",
         "| planet shape | projected ellipse (r, f, theta) | triaxial, 3-D orientation; projected ellipse | oblate spheroid | triaxial ellipsoid |",
         "| exposures | contact rule, supersampling | oversampling | supersampling | binning |",
         "| many parameter sets | native batch | jax.vmap | Python loop | native batch |", "",
         "The odd powers of mu (the standard quadratic law) are not available "
         "to MetalPlanet for an oblate planet -- they have no elementary form "
         "along an ellipse; the hybrid laws are as accurate as the four-"
         "parameter Claret law for real stars (README).", "",
         f"## Precision vs a 30-digit mpmath integral ({N_PREC} points)", "",
         "| code | central transit, max | central, median | graze (b = 1.02, f = 0.4, 60 deg), max |",
         "|---|---:|---:|---:|"]
    pg = r.get("precision_graze", {})
    for code, v in sorted(r["precision"].items(), key=lambda kv: kv[1]["max"]):
        g = pg.get(code, {}).get("max")
        L.append(f"| {NAMES[code]} | {v['max']:.2e} | {v['median']:.2e} | "
                 + (f"{g:.2e}" if g is not None else "--") + " |")
    L += ["", "The fp64 codes all reach rounding on these transits (JoJo's 100-step "
          "line integral is converged for this smooth profile); the fp32 codes "
          "sit at their precision's level, GreenLantern's set by its 2048-sample "
          "Simpson rule.", "",
          "## Single light curve: wall time vs N (median)", ""]
    ns = sorted({int(n) for v in r["single"].values() for n in v})
    L.append("| code | " + " | ".join(f"N = {n:,d}" for n in ns) + " |")
    L.append("|---|" + "---:|" * len(ns))
    for code, v in r["single"].items():
        L.append(f"| {NAMES[code]} | " + " | ".join(
            ms(v[str(n)]) if str(n) in v else "--" for n in ns) + " |")
    s = r["single"]
    if "10000000" in s.get("metalplanet_fp32", {}):
        base = s["metalplanet_fp32"]["10000000"]
        rows = [(NAMES[c], v["10000000"] / base) for c, v in s.items()
                if "10000000" in v and c != "metalplanet_fp32"]
        L += ["", "At N = 10^7 MetalPlanet's fp32 kernel is " + ", ".join(
            f"{x:,.0f}x faster than {n}" for n, x in sorted(rows, key=lambda q: q[1])) + "."]
    L += ["", "Below ~10^4 points the GPU dispatch floor (~1.6 ms, including the "
          "per-call contact solve) dominates MetalPlanet's fp32 route and the CPU "
          "codes are faster, as for spherical planets.", "",
          f"## Many parameter sets: {BATCH_NPV} sets x {BATCH_NPT:,d} points", "",
          "| code | wall | curves/s | how |", "|---|---:|---:|---|"]
    how = {"metalplanet_fp32": "TransitModel.light_curves, one launch",
           "squishyplanet": "jax.jit(jax.vmap(lightcurve))",
           "jojo": "Python loop (no batch API)",
           "greenlantern": "one launch, a parameter row per set"}
    for code, t in sorted(r["batch"].items(), key=lambda kv: kv[1]):
        L.append(f"| {NAMES[code]} | {t:.3f} s | {BATCH_NPV / t:,.0f} | {how[code]} |")
    L += ["", "## Value + gradient of a scalar loss (single light curve)", "",
          "In every parameter each code exposes: for MetalPlanet rp, f, theta, "
          "inc, t0, period, a and the limb-darkening weight. JoJo has no "
          "gradients.", ""]
    gn = sorted({int(n) for v in r["grad"].values() for n in v})
    L.append("| code | " + " | ".join(f"N = {n:,d}" for n in gn) + " |")
    L.append("|---|" + "---:|" * len(gn))
    for code, v in r["grad"].items():
        L.append(f"| {NAMES[code]} | " + " | ".join(
            ms(v[str(n)]) if str(n) in v else "--" for n in gn) + " |")
    L.append("")
    open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
